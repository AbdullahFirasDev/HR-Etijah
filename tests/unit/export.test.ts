import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'
import ExcelJS from 'exceljs'
import { describe, expect, it } from 'vitest'
import { reportToPdf, reportToXlsx, type PdfFonts } from '~~/server/utils/export'

const ROOT = resolve(import.meta.dirname, '../..')
const font = (f: string) => readFileSync(join(ROOT, 'server/assets/fonts', f))
const fonts: PdfFonts = {
  'ar': font('NotoSansArabic-Regular.ttf'),
  'ar-b': font('NotoSansArabic-Bold.ttf'),
  'la': font('NotoSans-Regular.ttf'),
  'la-b': font('NotoSans-Bold.ttf'),
}

const people = [
  { employeeId: 'e1', code: 'E004', name: 'علي جبار', nameEn: 'Ali Jabbar', departmentAr: 'العمليات', departmentEn: 'Operations' },
  { employeeId: 'e2', code: 'E005', name: 'سارة محمد', nameEn: 'Sara Mohammed', departmentAr: 'المبيعات', departmentEn: 'Sales' },
]
const monthly = {
  type: 'monthly',
  from: '2026-10-01',
  to: '2026-10-31',
  timezone: 'Asia/Baghdad',
  basis: 'daily',
  employees: 2,
  totals: { netMinutes: 18_900, requiredMinutes: 18_240, overtimeMinutes: 960, shortageMinutes: 300, lateCount: 3, absenceDays: 1, leaveDays: 2 },
  items: people.map((p, i) => ({
    ...p,
    period: '2026-10',
    from: '2026-10-01',
    to: '2026-10-31',
    netMinutes: 9_450 + i * 10,
    requiredMinutes: 9_120,
    overtimeMinutes: 480,
    shortageMinutes: 150,
    lateCount: i + 1,
    lateMinutes: 25,
    absenceDays: i,
    leaveDays: 1,
    holidayDays: 1,
    workingDays: 19,
    presentDays: 18 - i,
    attendancePercentage: 96.5 - i * 5,
  })),
}
const daily = {
  ...monthly,
  type: 'daily',
  items: people.map(p => ({
    ...p,
    date: '2026-10-28',
    status: 'present',
    checkIn: '2026-10-28T05:05:00Z',
    checkOut: '2026-10-28T13:40:00Z',
    netMinutes: 515,
    requiredMinutes: 480,
    breakMinutes: 30,
    lateMinutes: 5,
    earlyLeaveMinutes: 0,
    overtimeMinutes: 35,
    shortageMinutes: 0,
    flags: [],
  })),
}
const meta = { orgName: 'الاتجاه للسياحة والسفر', generatedBy: 'زينب حسن', timezone: 'Asia/Baghdad' }

describe('report exports', () => {
  it('produces an Arabic RTL Excel workbook with numeric hour columns', async () => {
    const buf = await reportToXlsx(monthly, 'monthly', 'ar', meta)
    const wb = new ExcelJS.Workbook()
    await wb.xlsx.load(buf as any)
    const ws = wb.worksheets[0]!
    expect(ws.views[0]?.rightToLeft).toBe(true)
    expect(ws.getRow(5).getCell(2).value).toBe('الموظف')
    expect(ws.getRow(6).getCell(2).value).toBe('علي جبار')
    // 9 450 minutes → 157.5 hours, stored as a number so Excel can sum it
    expect(ws.getRow(6).getCell(5).value).toBe(157.5)
    expect(ws.getRow(6 + monthly.items.length).getCell(1).value).toBe('المجموع')
  })

  it('produces an English LTR Excel workbook', async () => {
    const wb = new ExcelJS.Workbook()
    await wb.xlsx.load(await reportToXlsx(daily, 'daily', 'en', { ...meta, orgName: 'Etijah' }) as any)
    const ws = wb.worksheets[0]!
    expect(ws.views[0]?.rightToLeft).toBe(false)
    expect(ws.getRow(6).getCell(2).value).toBe('Ali Jabbar')
    // check-in rendered in Baghdad time (UTC+3)
    expect(ws.getRow(6).getCell(6).value).toBe('08:05')
  })

  it('produces valid PDFs in both languages with embedded fonts', async () => {
    const outDir = join(ROOT, 'test-results')
    mkdirSync(outDir, { recursive: true })
    for (const [report, type, lang] of [[monthly, 'monthly', 'ar'], [daily, 'daily', 'ar'], [daily, 'daily', 'en']] as const) {
      const pdf = await reportToPdf(report, type, lang, meta, fonts)
      expect(pdf.subarray(0, 5).toString()).toBe('%PDF-')
      expect(pdf.toString('latin1')).toContain('NotoSansArabic')
      writeFileSync(join(outDir, `export-${type}-${lang}.pdf`), pdf)
    }
  })
})

describe('PDF bidi word ordering', async () => {
  const { visualOrder } = await import('~~/server/utils/export')
  const draw = (text: string, base: 'rtl' | 'ltr') => {
    const tokens = text.split(' ')
    return visualOrder(tokens, base).map(i => tokens[i]).join(' ')
  }

  it('reverses an Arabic phrase for left-to-right drawing', () => {
    expect(draw('تقرير الحضور الشهري', 'rtl')).toBe('الشهري الحضور تقرير')
  })

  it('keeps Latin runs in reading order inside RTL text', () => {
    expect(draw('أنشئ في 2026-10-31 14:05 UTC', 'rtl')).toBe('2026-10-31 14:05 UTC في أنشئ')
  })

  it('keeps English order in an LTR line and reverses only the embedded Arabic run', () => {
    expect(draw('الاتجاه للسياحة — Daily attendance report', 'ltr')).toBe('للسياحة الاتجاه — Daily attendance report')
    expect(draw('Generated by: زينب حسن — 2026-10-31', 'ltr')).toBe('Generated by: حسن زينب — 2026-10-31')
  })
})
